export const dictionaries: Record<Locale, Dictionary> = { en, es, fr, de, pt, ar, zh, hi };

/**
 * Pure translation lookup (no React): resolve `key` for `locale`, falling back to
 * the default locale's dictionary and finally to the key itself, then apply
 * optional `{name}` interpolation. Extracted so the money-free i18n core is
 * unit-testable and reused verbatim by the provider.
 */
export function translate(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const dict = dictionaries[locale] ?? dictionaries[DEFAULT_LOCALE];
  const base = dictionaries[DEFAULT_LOCALE];
  const raw = dict[key] ?? base[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name) =>
    vars[name] != null ? String(vars[name]) : match,
  );
}
