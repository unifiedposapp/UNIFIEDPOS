export const CURRENCY_COUNT = CURRENCIES.length;

// Fast lookup by alpha-3 code.
export const CURRENCY_BY_CODE: Record<string, CurrencyInfo> = Object.fromEntries(
  CURRENCIES.map((c) => [c.code, c])
);

export function isValidCurrency(code: string): boolean {
  return !!CURRENCY_BY_CODE[(code || '').toUpperCase()];
}

// Symbol fallback for codes without a common symbol (metals, funds codes...).
export function currencySymbol(code: string): string {
  return CURRENCY_BY_CODE[(code || '').toUpperCase()]?.symbol || code.toUpperCase();
}
